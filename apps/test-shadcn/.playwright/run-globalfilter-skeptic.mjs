import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SHOTS = path.join(__dirname, 'screenshots');
const BASE = process.env.SRT_BASE || 'http://localhost:5404/';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1500, height: 1100 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.waitForTimeout(600);
const region = page.locator('#srt-inputs-menus-layout');
await region.scrollIntoViewIfNeeded();
const SEL = '#srt-inputs-menus-layout [data-slot="collapsible-content"]:has(input[placeholder="Search"])';
const toggle = region.locator('button[aria-label="Show/Hide search"]').first();
if (!(await page.locator(SEL).count())) { await toggle.click({ force: true }); await page.waitForTimeout(600); }
const input = page.locator(SEL).locator('input');
await input.focus();
await page.waitForTimeout(100);
const m = await page.evaluate((sel) => {
  const el = document.querySelector(sel);
  const grp = el.querySelector('[data-slot="input-group"]');
  const r = (e) => { const b = e.getBoundingClientRect(); return { x: b.x, y: b.y, w: b.width, h: b.height }; };
  const cs = getComputedStyle(el);
  return { content: r(el), group: r(grp), overflow: cs.overflow, anim: cs.animationName, groupShadow: getComputedStyle(grp).boxShadow, padding: cs.padding, focused: document.activeElement === el.querySelector('input') };
}, SEL);
console.log(JSON.stringify(m, null, 1));
const b = m.content;
await page.screenshot({ path: path.join(SHOTS, 'globalfilter-skeptic-focus.png'), clip: { x: b.x - 20, y: b.y - 20, width: b.w + 40, height: b.h + 40 } });
await browser.close();
