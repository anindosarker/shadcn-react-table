import { chromium } from 'playwright';
const BASE = process.env.SRT_BASE || 'http://localhost:5273/';
const browser = await chromium.launch({ headless: true });
const page = await (await browser.newContext({ viewport: { width: 1500, height: 1100 } })).newPage();
page.on('console', async (m) => { if (m.type() === 'error') { const args = await Promise.all(m.args().map((a) => a.jsonValue().catch(() => ''))); console.log('ERROR>>', args.join(' ').slice(0, 1500)); } });
await page.goto(BASE, { waitUntil: 'networkidle' }); console.log('--- loaded');
await page.waitForTimeout(600);
const region = page.locator('#srt-inputs-menus-layout');
await region.scrollIntoViewIfNeeded();
console.log('--- before toggle'); const toggle = region.locator('button[aria-label="Show/Hide search"]').first();
await toggle.click({ force: true }); await page.waitForTimeout(500);
const SEL = '#srt-inputs-menus-layout [data-slot="collapsible-content"]:has(input[placeholder="Search"])';
const input = page.locator(SEL).locator('input');
console.log('--- fill');
await input.fill('zzzzqqq'); await page.waitForTimeout(700);
console.log('--- clear');
await page.locator(SEL).locator('button[aria-label="Clear search"]').click({ force: true }); await page.waitForTimeout(700);
console.log('--- done');
await browser.close();
