import { chromium } from 'playwright';
const BASE = process.env.SRT_BASE || 'http://localhost:5368/';
const LAYOUT = '#srt-inputs-menus-layout';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1400 } });
const msgs = [];
page.on('console', (m) => { if (['error','warning'].includes(m.type()) && !/React DevTools/.test(m.text())) msgs.push(m.type()+': '+m.text()); });
page.on('pageerror', (e) => msgs.push('PAGEERROR: ' + e.message));
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.waitForSelector(LAYOUT, { timeout: 15000 });
const scan = () => page.evaluate((LAYOUT) => {
  const thead = document.querySelector(`${LAYOUT} thead`);
  const btns = [...thead.querySelectorAll('button')].filter(b => /scale-75/.test(b.className));
  return btns.map(b => { const r = b.getBoundingClientRect(); const cs = getComputedStyle(b); const svg = b.querySelector('svg')?.getBoundingClientRect();
    return { w: Math.round(r.width), h: Math.round(r.height), opacity: cs.opacity, transform: cs.transform, ml: cs.marginLeft, transition: cs.transitionDuration + ' ' + cs.transitionTimingFunction, cls: b.className, parentFlex: getComputedStyle(b.parentElement).flex, svgW: svg && Math.round(svg.width), type: b.type, aria: b.getAttribute('aria-label') }; });
}, LAYOUT);
console.log('before filter:', JSON.stringify(await scan()));
const input = page.locator(`${LAYOUT} thead input`).first();
await input.fill('a');
await page.waitForTimeout(300);
const after = await scan();
console.log('after filter:', JSON.stringify(after));
// hover tooltip
const btn = page.locator(`${LAYOUT} thead button.scale-75`).first();
await btn.hover(); await page.waitForTimeout(900);
const tip = await page.locator('[data-slot="tooltip-content"]').first().textContent().catch(() => null);
console.log('tooltip:', tip);
await page.locator('body').click({ position: { x: 5, y: 5 } });
await input.blur();
await btn.click(); await page.waitForTimeout(200);
console.log('focused after click:', await page.evaluate(() => document.activeElement?.tagName + ' ' + (document.activeElement?.value ?? '')));
console.log('msgs:', msgs);
await browser.close();
