import { chromium } from 'playwright';
const BASE = process.env.SRT_BASE ?? 'http://localhost:5273/';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const log = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') log.push([Date.now(), m.text().slice(0, 80), m.location()?.url?.slice(-60)]); });
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.waitForSelector('#layout', { timeout: 15000 });
await page.waitForTimeout(800);
console.log('after load', log);
const rows = page.locator('#layout tbody [role="checkbox"]');
await rows.nth(1).click(); await page.waitForTimeout(300);
console.log('after click', log.length);
await browser.close();
